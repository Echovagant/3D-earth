/** 这份表覆盖的 34 个 adcode，按代码升序 */
export const SHAPE_MEMORY_ADCODES = Object.keys(PROVINCE_SHAPE_MEMORIES).sort()

/**
 * 取一个省的形象记忆文案。
 *
 * 取不到（比如传进来的是南海断续线这种非省级要素）时返回 null，
 * 调用方自己决定怎么兜底。
 */
export function getShapeMemory(adcode) {
  const key = String(adcode ?? '')
  if (!PROVINCE_ADCODE_PATTERN.test(key)) return null
  return PROVINCE_SHAPE_MEMORIES[key] ?? null
}
